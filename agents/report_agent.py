"""
Report Agent.

Generates final research reports,
PDF exports and workflow history.

Author:
    Babu Guduru

Project:
    Agentic Research Scientist

Version:
    0.8
"""

from utils.logger import logger

from utils.cache_manager import (
    save_report_history
)

from utils.pdf_generator import (
    generate_pdf_report
)


def report_agent(state):
    """
    Generate final report.
    """

    logger.info(
        "Report Agent Started"
    )

    approval_status = (
        state.get(
            "approval",
            "no"
        ).lower()
    )

    # --------------------------------------------------
    # Rejected Report
    # --------------------------------------------------

    if approval_status != "yes":

        state["report"] = (
            "Research report was not "
            "generated because the "
            "hypothesis was rejected."
        )

        state["pdf_path"] = ""

        return state

    # --------------------------------------------------
    # Statistical Findings
    # --------------------------------------------------

    analysis_text = "\n".join(
        [
            f"{feature.title():<20}: "
            f"{float(value):.4f}"
            for feature, value in
            state["analysis"].items()
        ]
    )

    # --------------------------------------------------
    # Build Report
    # --------------------------------------------------

    report = f"""
==================================================
FINAL RESEARCH REPORT
==================================================

Research Question
--------------------------------------------------

{state['question']}

Evidence Summary
--------------------------------------------------

Research Papers Reviewed:
{len(state['evidence'])}

Statistical Findings
--------------------------------------------------

{analysis_text}

Scientific Analysis
--------------------------------------------------

{state['hypothesis']}

Review Status
--------------------------------------------------

APPROVED

Report Metadata
--------------------------------------------------

Generated By:
Agentic Research Scientist

Workflow Version:
0.8

==================================================
END OF REPORT
==================================================
"""

    state["report"] = report

    # --------------------------------------------------
    # PDF Export
    # --------------------------------------------------

    pdf_path = generate_pdf_report(
        question=state["question"],
        report=report
    )

    state["pdf_path"] = pdf_path

    # --------------------------------------------------
    # Save History
    # --------------------------------------------------

    save_report_history(
        question=state["question"],
        hypothesis=state["hypothesis"],
        approval=state["approval"]
    )

    logger.info(
        "Report generation completed."
    )

    return state