"""
Report Agent.

Responsible for generating the final
research report after human approval.

A report is only produced when
the hypothesis has been approved.

Author:
    Babu Guduru

Project:
    Agentic Research Scientist
"""


def report_agent(state):
    """
    Generate final research report.

    Args:
        state (dict):
            Current workflow state.

    Returns:
        dict:
            Updated workflow state containing
            the final report.
    """

    approval_status = state["approval"]

    if approval_status != "yes":

        state["report"] = (
            "Research report was not generated "
            "because the hypothesis was rejected."
        )

        return state

    report = f"""
==================================================
FINAL RESEARCH REPORT
==================================================

Research Question:
{state['question']}

--------------------------------------------------

Evidence Collected:
{len(state['evidence'])} research papers reviewed.

--------------------------------------------------

Statistical Findings:

{state['analysis']}

--------------------------------------------------

Hypothesis:

{state['hypothesis']}

--------------------------------------------------

Review Status:

APPROVED

--------------------------------------------------

Generated By:
Agentic Research Scientist
"""

    state["report"] = report

    return state