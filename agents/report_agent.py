"""
Report Agent.

Responsible for generating the final
research report after human approval.

A report is only produced when the
hypothesis has been approved by the
reviewer.

Author:
    Babu Guduru

Project:
    Agentic Research Scientist

Version:
    0.3
"""


def report_agent(state):
    """
    Generate a final research report.

    This agent consolidates:

    - Research Question
    - Literature Evidence
    - Statistical Findings
    - Scientific Hypothesis
    - Human Review Decision

    into a structured report.

    Args:
        state (dict):
            Current workflow state.

    Returns:
        dict:
            Updated workflow state containing
            the final report.
    """

    # ----------------------------------------------------------
    # Check Approval Status
    # ----------------------------------------------------------

    approval_status = state["approval"]

    if approval_status != "yes":

        state["report"] = (
            "Research report was not generated "
            "because the hypothesis was rejected."
        )

        return state

    # ----------------------------------------------------------
    # Format Statistical Findings
    # ----------------------------------------------------------

    analysis_text = "\n".join(
        [
            f"{feature.title():<20}: {float(value):.4f}"
            for feature, value in state["analysis"].items()
        ]
    )

    # ----------------------------------------------------------
    # Generate Report
    # ----------------------------------------------------------

    report = f"""
==================================================
FINAL RESEARCH REPORT
==================================================

Research Question:
{state['question']}

--------------------------------------------------

Evidence Summary:

Research Papers Reviewed:
{len(state['evidence'])}

--------------------------------------------------

Statistical Findings:

{analysis_text}

--------------------------------------------------

Scientific Hypothesis:

{state['hypothesis']}

--------------------------------------------------

Review Status:

APPROVED

--------------------------------------------------

Report Metadata:

Generated By:
Agentic Research Scientist

Workflow Version:
0.3

--------------------------------------------------

END OF REPORT
==================================================
"""

    state["report"] = report

    return state