from utils.cache_manager import (
    save_report_history
)


def report_agent(state):
    """
    Generate approved research report.

    Args:
        state (dict):
            Workflow state.

    Returns:
        dict:
            Updated workflow state.
    """

    approval_status = state["approval"]

    if approval_status != "yes":

        state["report"] = (
            "Research report was not generated "
            "because the hypothesis was rejected."
        )

        return state

    analysis_text = "\n".join(
        [
            f"{feature.title():<20}: {float(value):.4f}"
            for feature, value in state["analysis"].items()
        ]
    )

    report = f"""
==================================================
FINAL RESEARCH REPORT
==================================================

Research Question
--------------------------------------------------

{state['question']}

Evidence Summary
--------------------------------------------------

Research Papers Reviewed:
{len(state['evidence'])}

Statistical Findings
--------------------------------------------------

{analysis_text}

Scientific Analysis
--------------------------------------------------

{state['hypothesis']}

Review Status
--------------------------------------------------

APPROVED

Report Metadata
--------------------------------------------------

Generated By:
Agentic Research Scientist

Workflow Version:
0.6

==================================================
END OF REPORT
==================================================
"""

    state["report"] = report

    save_report_history(
        question=state["question"],
        hypothesis=state["hypothesis"],
        approval=state["approval"]
    )

    return state