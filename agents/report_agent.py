"""
Report Agent.

Responsible for generating the final
research report after human approval.

Features:

1. Report Generation
2. PDF Report Creation
3. Research History Persistence
4. Workflow State Updates

Author:
    Babu Guduru

Project:
    Agentic Research Scientist

Version:
    0.7
"""

from utils.logger import logger

from utils.cache_manager import (
    save_report_history
)

from utils.pdf_generator import (
    generate_pdf_report
)


def report_agent(state):
    """
    Generate final research report.

    This agent:

    1. Verifies approval status.
    2. Builds the final report.
    3. Generates a PDF report.
    4. Saves workflow history.
    5. Updates workflow state.

    Args:
        state (dict):
            Current workflow state.

    Returns:
        dict:
            Updated workflow state.
    """

    logger.info(
        "Report Agent Started"
    )

    approval_status = (
        state.get(
            "approval",
            "no"
        ).lower()
    )

    #
    # Handle rejected hypothesis
    #
    if approval_status != "yes":

        report = (
            "Research report was not generated "
            "because the hypothesis was rejected."
        )

        state["report"] = report
        state["pdf_path"] = ""

        logger.warning(
            "Report generation skipped. "
            "Hypothesis rejected."
        )

        return state

    #
    # Format statistical findings
    #
    analysis_text = "\n".join(
        [
            f"{feature.title():<20}: "
            f"{float(value):.4f}"
            for feature, value in
            state["analysis"].items()
        ]
    )

    #
    # Build report
    #
    report = f"""
==================================================
FINAL RESEARCH REPORT
==================================================

Research Question
--------------------------------------------------

{state['question']}

Evidence Summary
--------------------------------------------------

Research Papers Reviewed:
{len(state['evidence'])}

Statistical Findings
--------------------------------------------------

{analysis_text}

Scientific Analysis
--------------------------------------------------

{state['hypothesis']}

Review Status
--------------------------------------------------

APPROVED

Report Metadata
--------------------------------------------------

Generated By:
Agentic Research Scientist

Workflow Version:
0.7

==================================================
END OF REPORT
==================================================
"""

    #
    # Save report to workflow state
    #
    state["report"] = report

    #
    # Generate PDF
    #
    pdf_path = generate_pdf_report(
        question=state["question"],
        report=report
    )

    state["pdf_path"] = pdf_path

    #
    # Save workflow history
    #
    save_report_history(
        question=state["question"],
        hypothesis=state["hypothesis"],
        approval=state["approval"]
    )

    logger.info(
        "Research history updated."
    )

    logger.info(
        "Report generation completed."
    )

    return state