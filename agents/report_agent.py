import os
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    PageBreak,
)

from utils.cache_manager import save_report_history


def generate_pdf_report(
    question: str,
    hypothesis: str,
    analysis: dict,
    evidence: list,
) -> str:
    """
    Create a PDF research report.

    Args:
        question (str):
            Research question.

        hypothesis (str):
            Generated hypothesis.

        analysis (dict):
            Statistical results.

        evidence (list):
            Retrieved papers.

    Returns:
        str:
            Path to generated PDF file.
    """

    os.makedirs("reports", exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    pdf_path = os.path.join(
        "reports",
        f"report_{timestamp}.pdf"
    )

    document = SimpleDocTemplate(pdf_path)

    styles = getSampleStyleSheet()

    story = []

    # Title
    story.append(
        Paragraph(
            "Agentic Research Scientist Report",
            styles["Title"]
        )
    )

    story.append(Spacer(1, 12))

    story.append(
        Paragraph(
            f"<b>Generated:</b> "
            f"{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 20))

    # Research Question
    story.append(
        Paragraph(
            "Research Question",
            styles["Heading1"]
        )
    )

    story.append(
        Paragraph(
            question,
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 12))

    # Hypothesis
    story.append(
        Paragraph(
            "Generated Hypothesis",
            styles["Heading1"]
        )
    )

    story.append(
        Paragraph(
            hypothesis,
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 12))

    # Statistical Findings
    story.append(
        Paragraph(
            "Statistical Findings",
            styles["Heading1"]
        )
    )

    for feature, value in analysis.items():
        story.append(
            Paragraph(
                f"<b>{feature.title()}</b>: "
                f"{float(value):.4f}",
                styles["BodyText"]
            )
        )

    story.append(Spacer(1, 12))

    # Evidence
    story.append(
        Paragraph(
            "Research Evidence",
            styles["Heading1"]
        )
    )

    if evidence:

        for index, paper in enumerate(
            evidence[:15],
            start=1
        ):

            title = paper.get(
                "title",
                "Unknown Title"
            )

            summary = paper.get(
                "summary",
                "No summary available."
            )

            story.append(
                Paragraph(
                    f"<b>{index}. {title}</b>",
                    styles["Heading2"]
                )
            )

            story.append(
                Paragraph(
                    summary[:1000],
                    styles["BodyText"]
                )
            )

            story.append(Spacer(1, 8))

    else:

        story.append(
            Paragraph(
                "No supporting research papers found.",
                styles["BodyText"]
            )
        )

    story.append(PageBreak())

    # Metadata
    story.append(
        Paragraph(
            "Report Metadata",
            styles["Heading1"]
        )
    )

    story.append(
        Paragraph(
            "Generated By: Agentic Research Scientist",
            styles["BodyText"]
        )
    )

    story.append(
        Paragraph(
            "Workflow Version: 1.0",
            styles["BodyText"]
        )
    )

    story.append(
        Paragraph(
            "Approval Status: APPROVED",
            styles["BodyText"]
        )
    )

    document.build(story)

    return pdf_path


def report_agent(state: dict) -> dict:
    """
    Generate final approved research report.

    Args:
        state (dict):
            Workflow state.

    Returns:
        dict:
            Updated workflow state.
    """

    approval_status = state.get(
        "approval",
        "no"
    )

    if approval_status.lower() != "yes":

        state["report"] = (
            "Research report was not generated "
            "because the hypothesis was rejected."
        )

        return state

    analysis_text = "\n".join(
        [
            f"{feature.title():<20}: {float(value):.4f}"
            for feature, value in state[
                "analysis"
            ].items()
        ]
    )

    report = f"""
==================================================
FINAL RESEARCH REPORT
==================================================

Research Question
--------------------------------------------------

{state['question']}

Evidence Summary
--------------------------------------------------

Research Papers Reviewed:
{len(state['evidence'])}

Statistical Findings
--------------------------------------------------

{analysis_text}

Scientific Analysis
--------------------------------------------------

{state['hypothesis']}

Review Status
--------------------------------------------------

APPROVED

Report Metadata
--------------------------------------------------

Generated By:
Agentic Research Scientist

Workflow Version:
1.0

==================================================
END OF REPORT
==================================================
"""

    state["report"] = report

    try:

        pdf_path = generate_pdf_report(
            question=state["question"],
            hypothesis=state["hypothesis"],
            analysis=state["analysis"],
            evidence=state["evidence"],
        )

        state["pdf_report"] = pdf_path

        print(
            f"\n✅ PDF Report Generated: "
            f"{pdf_path}"
        )

    except Exception as error:

        print(
            f"\n❌ PDF Generation Failed: "
            f"{error}"
        )

        state["pdf_report"] = None

    save_report_history(
        question=state["question"],
        hypothesis=state["hypothesis"],
        approval=state["approval"]
    )

    return state