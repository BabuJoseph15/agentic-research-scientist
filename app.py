"""
Agentic Research Scientist.

Main application entry point.

This module executes the LangGraph workflow
and displays outputs generated by all agents.

Workflow:

    Research Agent
          ↓
    Evidence Agent
          ↓
    Analysis Agent
          ↓
    GPT-4o Hypothesis Agent
          ↓
    Approval Agent
          ↓
    Report Agent
          ↓
    PDF Generation
          ↓
    History Persistence
          ↓
          END

Author:
    Babu Guduru

Project:
    Agentic Research Scientist

Version:
    0.7
"""

from graph.workflow import graph


def main():
    """
    Execute the Agentic Research Scientist workflow.

    Returns:
        None
    """

    # --------------------------------------------------
    # Initial Workflow State
    # --------------------------------------------------

    initial_state = {
        "question": (
            "Can climate change increase "
            "dengue outbreaks in India?"
        ),
        "papers": [],
        "evidence": [],
        "analysis": {},
        "hypothesis": "",
        "approval": "",
        "report": "",
        "pdf_path": ""
    }

    # --------------------------------------------------
    # Execute Workflow
    # --------------------------------------------------

    result = graph.invoke(initial_state)

    # --------------------------------------------------
    # Research Papers
    # --------------------------------------------------

    print("\n" + "=" * 100)
    print("RESEARCH PAPERS FOUND")
    print("=" * 100)

    for index, paper in enumerate(
        result["papers"],
        start=1
    ):

        print(f"\nPaper {index}")
        print("-" * 100)

        print(
            f"Title      : "
            f"{paper.get('title', 'N/A')}"
        )

        print(
            f"Published  : "
            f"{paper.get('published', 'N/A')}"
        )

        authors = paper.get(
            "authors",
            []
        )

        print(
            f"Authors    : "
            f"{', '.join(authors)}"
        )

        print(
            f"URL        : "
            f"{paper.get('url', 'N/A')}"
        )

    # --------------------------------------------------
    # Evidence
    # --------------------------------------------------

    print("\n" + "=" * 100)
    print("EVIDENCE EXTRACTED")
    print("=" * 100)

    for index, evidence in enumerate(
        result["evidence"],
        start=1
    ):

        print(f"\nEvidence {index}")

        print(
            f"Title      : "
            f"{evidence.get('title', 'N/A')}"
        )

        print(
            f"Published  : "
            f"{evidence.get('published', 'N/A')}"
        )

    # --------------------------------------------------
    # Statistical Analysis
    # --------------------------------------------------

    print("\n" + "=" * 100)
    print("CORRELATION ANALYSIS")
    print("=" * 100)

    if result.get("analysis"):

        for (
            feature,
            correlation
        ) in result["analysis"].items():

            print(
                f"{feature:<25} : "
                f"{correlation}"
            )

    else:

        print(
            "No analysis findings available."
        )

    # --------------------------------------------------
    # GPT Generated Hypothesis
    # --------------------------------------------------

    print("\n" + "=" * 100)
    print("GPT GENERATED HYPOTHESIS")
    print("=" * 100)

    print(
        result.get(
            "hypothesis",
            "No hypothesis generated."
        )
    )

    # --------------------------------------------------
    # Approval Status
    # --------------------------------------------------

    print("\n" + "=" * 100)
    print("APPROVAL STATUS")
    print("=" * 100)

    approval = result.get(
        "approval",
        "unknown"
    )

    print(
        f"Decision : {approval.upper()}"
    )

    # --------------------------------------------------
    # Final Report
    # --------------------------------------------------

    print("\n" + "=" * 100)
    print("FINAL REPORT")
    print("=" * 100)

    print(
        result.get(
            "report",
            "No report generated."
        )
    )

    # --------------------------------------------------
    # PDF Report
    # --------------------------------------------------

    pdf_path = result.get(
        "pdf_path",
        ""
    )

    if pdf_path:

        print("\n" + "=" * 100)
        print("PDF REPORT")
        print("=" * 100)

        print(
            f"Generated File : "
            f"{pdf_path}"
        )


if __name__ == "__main__":
    main()