"""
Agentic Research Scientist.

Main application entry point.

This module initializes the workflow state,
executes the LangGraph workflow, and displays
results generated by each agent.

Workflow:

    Research Agent
          ↓
    Evidence Agent
          ↓
    Analysis Agent
          ↓
    Hypothesis Agent
          ↓
    Approval Agent
          ↓
    Report Agent
          ↓
          END

Author:
    Babu Guduru

Project:
    Agentic Research Scientist

Version:
    0.2
"""

from graph.workflow import graph


def main():
    """
    Execute Agentic Research Scientist workflow.

    Returns:
        None
    """

    # ----------------------------------------------------------
    # Initialize Workflow State
    # ----------------------------------------------------------

    initial_state = {
        "question": (
            "Can climate change increase "
            "dengue outbreaks in India?"
        ),
        "papers": [],
        "evidence": [],
        "analysis": {},
        "hypothesis": "",
        "approval": "",
        "report": ""
    }

    # ----------------------------------------------------------
    # Execute Workflow
    # ----------------------------------------------------------

    result = graph.invoke(initial_state)

    # ----------------------------------------------------------
    # Debug Information
    # ----------------------------------------------------------

    print("\n")
    print("=" * 100)
    print("DEBUG RESULT KEYS")
    print("=" * 100)

    print(result.keys())

    # ----------------------------------------------------------
    # Research Papers
    # ----------------------------------------------------------

    print("\n" + "=" * 100)
    print("RESEARCH PAPERS FOUND")
    print("=" * 100)

    for idx, paper in enumerate(result["papers"], start=1):

        print(f"\nPaper {idx}")
        print("-" * 100)

        print(
            f"Title      : {paper['title']}"
        )

        print(
            f"Published  : {paper['published']}"
        )

        print(
            f"Authors    : "
            f"{', '.join(paper['authors'])}"
        )

        print(
            f"URL        : {paper['url']}"
        )

    # ----------------------------------------------------------
    # Evidence
    # ----------------------------------------------------------

    print("\n" + "=" * 100)
    print("EVIDENCE EXTRACTED")
    print("=" * 100)

    for idx, evidence in enumerate(
        result["evidence"],
        start=1
    ):

        print(f"\nEvidence {idx}")

        print(
            f"Title      : "
            f"{evidence['title']}"
        )

        print(
            f"Published  : "
            f"{evidence['published']}"
        )

    # ----------------------------------------------------------
    # Correlation Analysis
    # ----------------------------------------------------------

    print("\n" + "=" * 100)
    print("CORRELATION ANALYSIS")
    print("=" * 100)

    if result["analysis"]:

        for feature, correlation in (
            result["analysis"].items()
        ):

            print(
                f"{feature:<25} : "
                f"{correlation}"
            )

    else:

        print(
            "No analysis results available."
        )

    # ----------------------------------------------------------
    # Hypothesis
    # ----------------------------------------------------------

    print("\n" + "=" * 100)
    print("HYPOTHESIS")
    print("=" * 100)

    print(result["hypothesis"])

    # ----------------------------------------------------------
    # Approval Status
    # ----------------------------------------------------------

    print("\n" + "=" * 100)
    print("APPROVAL STATUS")
    print("=" * 100)

    print(
        f"Decision : "
        f"{result.get('approval', 'NOT AVAILABLE').upper()}"
    )

    # ----------------------------------------------------------
    # Final Report
    # ----------------------------------------------------------

    print("\n" + "=" * 100)
    print("FINAL REPORT")
    print("=" * 100)

    print(
        result.get(
            "report",
            "No report generated."
        )
    )


if __name__ == "__main__":
    main()